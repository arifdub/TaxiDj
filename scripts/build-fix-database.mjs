// Builds supabase/fix-database.sql: every migration after the initial schema,
// rewritten so it can be run on a Taxi DJ database in ANY state (missing some
// updates, or fully up to date) and run again safely. Owners who don't use
// the Supabase CLI paste it into Supabase → SQL Editor → Run.
//
// Run after adding a migration:  node scripts/build-fix-database.mjs
import fs from "node:fs";
import path from "node:path";

const dir = path.join(import.meta.dirname, "..", "supabase", "migrations");
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .slice(1); // the initial schema is always applied first

function idempotent(sql) {
  return (
    sql
      .replace(/\bcreate function\b/gi, "create or replace function")
      .replace(/\badd column (?!if not exists)/gi, "add column if not exists ")
      .replace(/\bcreate table (?!if not exists)/gi, "create table if not exists ")
      .replace(/\bcreate index (?!if not exists)/gi, "create index if not exists ")
      .replace(/\bdrop constraint (?!if exists)/gi, "drop constraint if exists ")
      .replace(/\bdrop function (?!if exists)/gi, "drop function if exists ")
      // Triggers and policies have no "if not exists": drop first.
      .replace(
        /\bcreate trigger (\w+)([\s\S]*?)\bon ([\w.]+)/gi,
        (m, name, mid, table) => `drop trigger if exists ${name} on ${table};\ncreate trigger ${name}${mid}on ${table}`,
      )
      .replace(
        /\bcreate policy ("[^"]+")([\s\S]*?)\bon ([\w.]+)/gi,
        (m, name, mid, table) => `drop policy if exists ${name} on ${table};\ncreate policy ${name}${mid}on ${table}`,
      )
  );
}

const out = [
  "-- =============================================================================",
  "-- Taxi DJ — FIX / UPDATE DATABASE (safe to run any time, as often as needed)",
  "--",
  "-- Brings a Taxi DJ database fully up to date, whatever updates it is missing.",
  "-- Supabase → SQL Editor → New query → paste this whole file → Run.",
  "-- Generated by scripts/build-fix-database.mjs from supabase/migrations/.",
  "-- =============================================================================",
  "",
];
for (const f of files) {
  out.push(`-- ---------------------------------------------------------------- ${f}`);
  out.push(idempotent(fs.readFileSync(path.join(dir, f), "utf8")).trim(), "");
}
out.push("-- Tell the API about any new or changed functions.", "notify pgrst, 'reload schema';", "");
fs.writeFileSync(path.join(dir, "..", "fix-database.sql"), out.join("\n"));
console.log(`supabase/fix-database.sql: ${files.length} updates`);
